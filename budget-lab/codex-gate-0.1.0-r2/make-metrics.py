#!/usr/bin/env python3
"""Generate METRICS.md from runs/*/metrics.json and runs/*/summary.json. Usage: python3 make-metrics.py"""
import json
from pathlib import Path

LAB = Path(__file__).resolve().parent
lines = ["# Metrics", "", "Generated by make-metrics.py from runs/*/metrics.json and runs/*/summary.json.", "",
         "| Case | Step | Command | Exit | Elapsed ms |", "|---|---|---|---:|---:|"]
calls = 0
tokens = {}
for case in sorted(p for p in (LAB / "runs").iterdir() if p.is_dir()):
    summary = json.loads((case / "summary.json").read_text())
    for row in json.loads((case / "metrics.json").read_text()):
        calls += 1
        argv = " ".join(str(a) for a in row["argv"][:4]).replace("|", "\\|")[:80]
        lines.append(f"| {case.name} | {row['step']} | `{argv}` | {row['exit']} | {row['elapsed_ms']} |")
    usage = [u for part in ("fresh", "resume") for u in (summary.get(part) or {}).get("usage", [])]
    if usage:
        tokens[case.name] = (sum((u or {}).get("input_tokens", 0) for u in usage),
                             sum((u or {}).get("cached_input_tokens", 0) for u in usage),
                             sum((u or {}).get("output_tokens", 0) for u in usage))
lines += ["", "| Case | Input tokens (fresh + resume) | Cached | Output |", "|---|---:|---:|---:|"]
lines += [f"| {k} | {a} | {b} | {c} |" for k, (a, b, c) in tokens.items()]
lines += ["", f"{calls} calls. Codex `input_tokens` include `cached_input_tokens` (`turn.completed` usage of the case's "
          "fresh and resume execs; the bootstrap is not included). Deltas: N/A."]
(LAB / "METRICS.md").write_text("\n".join(lines) + "\n")
print(calls, tokens)
