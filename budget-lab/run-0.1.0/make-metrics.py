#!/usr/bin/env python3
"""Generate METRICS.md from runs/*/metrics.json and runs/*/summary.json. Usage: python3 make-metrics.py"""
import json
from pathlib import Path

LAB = Path(__file__).resolve().parent
lines = ["# Metrics", "", "Generated by make-metrics.py from runs/*/metrics.json and runs/*/summary.json.", "",
         "| Case | Step | Command | Exit | Elapsed ms |", "|---|---|---|---:|---:|"]
tokens, calls = [], 0
for case in sorted(p for p in (LAB / "runs").iterdir() if p.is_dir()):
    summary = json.loads((case / "summary.json").read_text())
    for row in json.loads((case / "metrics.json").read_text()):
        calls += 1
        argv = " ".join(str(a) for a in row["argv"][:4]).replace("|", "\\|")[:80]
        lines.append(f"| {case.name} | {row['step']} | `{argv}` | {row['exit']} | {row['elapsed_ms']} |")
    if "elapsed_ms" in summary:
        lines.append(f"| {case.name} | interactive session | `claude` (tmux) | | {summary['elapsed_ms']} |")
    usage = [u for part in ("bootstrap", "first", "answer") for u in (summary.get(part) or {}).get("usage", [])]
    if usage:
        tokens.append((case.name, sum(u.get("input_tokens", 0) for u in usage),
                       sum(u.get("cached_input_tokens", 0) for u in usage), sum(u.get("output_tokens", 0) for u in usage)))
lines += ["", "| Codex case | Input tokens | Cached | Output |", "|---|---:|---:|---:|"]
lines += [f"| {n} | {a} | {b} | {c} |" for n, a, b, c in tokens]
lines += ["", f"{calls} subprocess calls. Codex tokens are the `turn.completed` usage of every exec in the case "
          "(bootstrap, first and answer). Interactive Claude sessions show no token counts. Deltas: N/A."]
(LAB / "METRICS.md").write_text("\n".join(lines) + "\n")
print(calls, tokens)
