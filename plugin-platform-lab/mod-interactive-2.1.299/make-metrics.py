#!/usr/bin/env python3
"""Generate METRICS.md from runs/*/summary.json. Usage: python3 make-metrics.py"""
import json
from pathlib import Path

LAB = Path(__file__).resolve().parent
lines = ["# Metrics", "", "Generated by make-metrics.py from runs/*/summary.json.", "",
         "| Case | Elapsed ms | Dialogs answered | Module rows |", "|---|---:|---:|---:|"]
for case in sorted(p for p in (LAB / "runs").iterdir() if p.is_dir() and p.name != "V00"):
    s = json.loads((case / "summary.json").read_text())
    lines.append(f"| {case.name} | {s.get('elapsed_ms')} | {s.get('dialogs_answered', '')} | {len(s.get('rows', []))} |")
lines += ["", "Elapsed ms = from starting the tmux session to the last snapshot, waits included. Interactive sessions "
          "expose no token counts or cost, so none are recorded. Deltas: N/A."]
(LAB / "METRICS.md").write_text("\n".join(lines) + "\n")
