#!/usr/bin/env python3
"""Post-hoc checks, written after the run (not in the frozen SPEC). Usage: python3 posthoc.py → POSTHOC.md

1. Leave-one-fixture-out per family, Fable excluded (it ran on one fixture only, so a held-out p2 left it unfitted).
2. Family-only factors vs family × category factors, leave-one-fixture-out.
3. Goal level: Σ estimate × factor vs Σ actual per cell, with factors fitted on the other fixtures.
"""
import importlib.util
import math
from pathlib import Path
import statistics

LAB = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("analysis", LAB / "analyze.py")
a = importlib.util.module_from_spec(spec)
spec.loader.exec_module(a)
rows = [r for r in a.usable(a.items()) if r["fam"] != "fable"]
fixtures = sorted({r["fixture"] for r in rows})


def family_only(train):
    return {f: {"all": cell["all"]} for f, cell in a.fit(train).items()}


lines = ["# Post-hoc checks (not in the frozen SPEC)", "", "Generated by posthoc.py. Fable excluded (one fixture).", "",
         "## Leave-one-fixture-out, Sonnet and Opus", "",
         "| Held-out | Family | n | Raw | Family × category | Family only |", "|---|---|---:|---:|---:|---:|"]
for held in fixtures:
    train = [r for r in rows if r["fixture"] != held]
    for fam in ("sonnet", "opus"):
        test = [r for r in rows if r["fixture"] == held and r["fam"] == fam]
        lines.append(f"| {held} | {fam} | {len(test)} | {a.error(test):.2f} | {a.error(test, a.fit(train)):.2f} | "
                     f"{a.error(test, family_only(train)):.2f} |")
allraw, allcat, allfam = [], [], []
for held in fixtures:
    train = [r for r in rows if r["fixture"] != held]
    test = [r for r in rows if r["fixture"] == held]
    for r in test:
        allraw.append(abs(math.log2(r["actual_min"] / r["est_min"])))
        allcat.append(abs(math.log2(r["actual_min"] / (r["est_min"] * a.factor(a.fit(train), r["fam"], r.get("cat"))))))
        allfam.append(abs(math.log2(r["actual_min"] / (r["est_min"] * a.factor(family_only(train), r["fam"], None)))))
lines += ["", f"All held-out items (n={len(allraw)}): median abs log2 raw {statistics.median(allraw):.2f}, family × "
          f"category {statistics.median(allcat):.2f}, family only {statistics.median(allfam):.2f}.", "",
          "## Goal level, leave-one-fixture-out", "", "| Cell | Σ est | Σ est × factor | Σ actual | abs log2 |",
          "|---|---:|---:|---:|---:|"]
goal_errs = []
for cell in sorted({r["cell"] for r in rows}):
    mine = [r for r in rows if r["cell"] == cell]
    fitted = a.fit([r for r in rows if r["fixture"] != mine[0]["fixture"]])
    est = sum(r["est_min"] for r in mine)
    pred = sum(r["est_min"] * a.factor(fitted, r["fam"], r.get("cat")) for r in mine)
    act = sum(r["actual_min"] for r in mine)
    goal_errs.append(abs(math.log2(act / pred)))
    lines.append(f"| {cell} | {est:.0f} | {pred:.1f} | {act:.1f} | {goal_errs[-1]:.2f} |")
lines += ["", f"Median goal-level abs log2: {statistics.median(goal_errs):.2f} "
          f"(within ±25 %: {sum(1 for e in goal_errs if e <= math.log2(1.25))} of {len(goal_errs)})."]
(LAB / "POSTHOC.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
