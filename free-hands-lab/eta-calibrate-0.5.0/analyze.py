#!/usr/bin/env python3
"""SPEC.md's analysis. Usage: python3 analyze.py  → METRICS.md, baseline-candidate.json, items.csv

Reads runs/<cell>/summary.json, free-hands-dir/timings.jsonl, free-hands-dir/goal.md and lab/witness.jsonl. Writes
nothing under runs/.
"""
import csv
import json
import math
from pathlib import Path
import statistics

LAB = Path(__file__).resolve().parent
RUNS = LAB / "runs"
SHRINK = 2


def cells():
    for path in sorted(RUNS.iterdir()):
        if path.name != "V00" and (path / "DONE").exists():
            yield path, json.loads((path / "summary.json").read_text())


def items():
    rows = []
    for path, notes in cells():
        timings = path / "free-hands-dir" / "timings.jsonl"
        for line in timings.read_text().splitlines() if timings.exists() else []:
            row = json.loads(line)
            row.update(cell=notes["cell"], fixture=notes["fixture"], fam=notes["family"], rep=notes["rep"])
            rows.append(row)
    return rows


def usable(rows):
    return [r for r in rows if r.get("outcome") == "done" and (r.get("est_min") or 0) > 0 and (r.get("actual_min") or 0) > 0]


def log2r(row):
    return math.log2(row["actual_min"] / row["est_min"])


def summary(rows):
    if not rows:
        return {"n": 0}
    logs = [log2r(r) for r in rows]
    return {"n": len(rows), "geo": 2 ** statistics.mean(logs), "median": 2 ** statistics.median(logs),
            "abs_log2": statistics.median(abs(x) for x in logs),
            "within50": sum(1 for r in rows if 0.5 <= r["actual_min"] / r["est_min"] <= 1.5) / len(rows)}


def fit(rows):
    """Factors per family: `all`, and per category with >= 3 items shrunk toward `all`."""
    out = {}
    for fam in sorted({r["fam"] for r in rows}):
        mine = [r for r in rows if r["fam"] == fam]
        if len(mine) < 5:
            continue
        mean_all = statistics.mean(log2r(r) for r in mine)
        cell = {"all": round(2 ** mean_all, 3), "n": len(mine)}
        if fam != "fable":
            for cat in sorted({r.get("cat") for r in mine if r.get("cat")}):
                logs = [log2r(r) for r in mine if r.get("cat") == cat]
                if len(logs) >= 3:
                    cell[cat] = round(2 ** ((sum(logs) + SHRINK * mean_all) / (len(logs) + SHRINK)), 3)
        out[fam] = cell
    return out


def factor(fitted, fam, cat):
    cell = fitted.get(fam) or {}
    return cell.get(cat) or cell.get("all") or 1.0


def error(rows, fitted=None):
    errs = [abs(math.log2(r["actual_min"] / (r["est_min"] * (factor(fitted, r["fam"], r.get("cat")) if fitted else 1.0))))
            for r in rows]
    return statistics.median(errs) if errs else None


def witness(path):
    """Wall-clock minutes from the goal file's first checklist to its last completion, per the witness."""
    log = path / "lab" / "witness.jsonl"
    if not log.exists():
        return None
    rows = [json.loads(line) for line in log.read_text().splitlines()]
    first = next((r["at"] for r in rows if r.get("marks")), None)
    done = [r["at"] for i, r in enumerate(rows) if i and sum(c in "xX-" for c in r.get("marks") or "") >
            sum(c in "xX-" for c in rows[i - 1].get("marks") or "")]
    return (max(done) - first) / 60.0 if first and done else None


def fmt(value, digits=2):
    return "" if value is None else (f"{value:.{digits}f}" if isinstance(value, float) else str(value))


def table(title, groups):
    lines = [f"### {title}", "", "| Group | n | Geo-mean ratio | Median ratio | Median abs log2 | Within ±50 % |",
             "|---|---:|---:|---:|---:|---:|"]
    for name, rows in groups:
        s = summary(rows)
        lines.append(f"| {name} | {s['n']} | {fmt(s.get('geo'))} | {fmt(s.get('median'))} | {fmt(s.get('abs_log2'))} | "
                     f"{fmt(s.get('within50') and s['within50'] * 100, 0)} |")
    return lines + [""]


def main():
    all_rows = items()
    rows = usable(all_rows)
    with open(LAB / "items.csv", "w", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["cell", "fixture", "family", "rep", "item", "cat", "est_min", "actual_min", "batch", "outcome",
                         "model", "effort"])
        for r in all_rows:
            writer.writerow([r["cell"], r["fixture"], r["fam"], r["rep"], r.get("item"), r.get("cat"), r.get("est_min"),
                             r.get("actual_min"), r.get("batch"), r.get("outcome"), r.get("model"), r.get("effort")])
    lines = ["# Metrics", "", "Generated by analyze.py from runs/*/. Ratio = actual / estimate (minutes); actual is the "
             "candidate recorder's active time (`timings.jsonl`). Median abs log2 = the raw estimate's typical error "
             "in doublings (0 = exact, 1 = off by 2x).", "", "## Cells", "",
             "| Cell | Model | Exit | Elapsed s | Cost USD | Turns | Tool uses | Advisor | Items rec. | Σ est min | "
             "Σ actual min | Witness min | Tests after |", "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    spent = 0.0
    for path, notes in cells():
        mine = [r for r in all_rows if r["cell"] == notes["cell"]]
        est = sum(r.get("est_min") or 0 for r in mine)
        act = sum(r.get("actual_min") or 0 for r in mine)
        spent += notes.get("cost") or 0.0
        lines.append(f"| {notes['cell']} | {notes.get('model')} | {notes.get('exit')} | {notes.get('elapsed_s')} | "
                     f"{fmt(notes.get('cost'))} | {notes.get('num_turns')} | {notes.get('tool_uses')} | "
                     f"{notes.get('advisor_calls')} | {len(mine)} | {fmt(float(est), 1)} | {fmt(float(act), 1)} | "
                     f"{fmt(witness(path), 1)} | {notes.get('tests_after', {}).get('exit')} |")
    lines += ["", f"Total cost {spent:.2f} USD (result `total_cost_usd`).", "", "## Estimate vs actual", ""]
    fams = sorted({r["fam"] for r in rows})
    lines += table("By family", [(f, [r for r in rows if r["fam"] == f]) for f in fams])
    lines += table("By family × category", [(f"{f} {c}", [r for r in rows if r["fam"] == f and r.get("cat") == c])
                                            for f in fams for c in sorted({r.get("cat") or "-" for r in rows})
                                            if any(r["fam"] == f and (r.get("cat") or "-") == c for r in rows)])
    lines += table("By fixture × family", [(f"{x} {f}", [r for r in rows if r["fixture"] == x and r["fam"] == f])
                                           for x in sorted({r["fixture"] for r in rows}) for f in fams])
    fitted = fit(rows)
    lines += ["## Leave-one-fixture-out", "", "| Held-out fixture | n | Raw median abs log2 | Calibrated median abs log2 |",
              "|---|---:|---:|---:|"]
    for held in sorted({r["fixture"] for r in rows}):
        train = [r for r in rows if r["fixture"] != held]
        test = [r for r in rows if r["fixture"] == held]
        lines.append(f"| {held} | {len(test)} | {fmt(error(test))} | {fmt(error(test, fit(train)))} |")
    lines += ["", f"In-sample (all fixtures): raw {fmt(error(rows))}, calibrated {fmt(error(rows, fitted))}.", "",
              "## Fitted factors", "", "```json", json.dumps(fitted, indent=1), "```", ""]
    (LAB / "METRICS.md").write_text("\n".join(lines) + "\n")
    (LAB / "baseline-candidate.json").write_text(json.dumps({"families": fitted}, indent=1) + "\n")
    print(json.dumps(fitted))


if __name__ == "__main__":
    main()
