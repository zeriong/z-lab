#!/usr/bin/env python3
"""SPEC.md's analysis. Usage: python3 analyze.py  → METRICS.md, items.csv, baseline-candidate.json"""
import csv
import json
import math
from pathlib import Path
import statistics

LAB = Path(__file__).resolve().parent
RUNS = LAB / "runs"
SELF = {"sonnet": 0.080, "opus": 0.126, "fable": 0.197, "default": 0.125}  # 0.5.0's shipped `self` factors


def log2(x):
    return math.log2(x)


def med(values):
    values = list(values)
    return statistics.median(values) if values else None


def main():
    goals = {g["id"]: g for g in json.loads((LAB / "inputs.json").read_text())}
    runs = [json.loads(p.read_text()) for p in sorted(RUNS.glob("*/summary.json")) if p.parent.name != "V00"
            and (p.parent / "DONE").exists()]
    by_goal = {}
    for run in runs:
        by_goal.setdefault(run["goal_run"], []).append(run)
    items = []
    for gid, goal in goals.items():
        reps = by_goal.get(gid, [])
        for item in goal["items"]:
            answers = [r["minutes"] for run in reps for r in run["rows"] if r["key"] == item["key"]]
            cats = [r["category"] for run in reps for r in run["rows"] if r["key"] == item["key"] and r["category"]]
            items.append({"goal_run": gid, "source": goal["source"], "fixture": goal["fixture"], "family": goal["family"],
                          "goal": goal["goal"], "key": item["key"][:90], "actual": item["actual"],
                          "self_est": item["self_est"], "haiku_runs": answers, "haiku": med(answers),
                          "category": max(set(cats), key=cats.count) if cats else None})
    with open(LAB / "items.csv", "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(items[0]))
        writer.writeheader()
        writer.writerows(items)
    usable = [i for i in items if i["actual"] and i["haiku"]]
    fit = [i for i in usable if i["goal"] == "A"]
    test = [i for i in usable if i["goal"] != "A"]
    factors = {}
    for fam in sorted({i["family"] for i in fit}):
        mine = [i for i in fit if i["family"] == fam]
        if len(mine) >= 5:
            factors[fam] = {"all": round(2 ** statistics.mean(log2(i["actual"] / i["haiku"]) for i in mine), 3),
                            "n": len(mine)}
    if factors:
        factors["default"] = {"all": round(statistics.mean(f["all"] for f in factors.values()), 3)}

    def factor(fam):
        return (factors.get(fam) or factors.get("default") or {"all": 1.0})["all"]

    def errors(rows, how):
        out = []
        for i in rows:
            if how == "raw":
                pred = i["haiku"]
            elif how == "haiku":
                pred = i["haiku"] * factor(i["family"])
            else:
                if not i["self_est"]:
                    continue
                pred = i["self_est"] * SELF.get(i["family"], SELF["default"])
            out.append(abs(log2(i["actual"] / pred)))
        return out

    spreads = [max(i["haiku_runs"]) / min(i["haiku_runs"]) for i in items if len(i["haiku_runs"]) >= 2]
    devs = [abs(log2(m / i["haiku"])) for i in items for m in i["haiku_runs"] if i["haiku"]]
    lines = ["# Metrics", "", "Generated by analyze.py. Error = |log2(measured / predicted)| per item (0 = exact, 1 = "
             "off by 2x). haiku = median of the three estimator runs; raw = that estimate; haiku×f = × the factor fitted "
             "on goal A; self×f = the working agent's own estimate × 0.5.0's shipped `self` factor.", "", "## Runs", "",
             f"{len(runs)} runs over {len(by_goal)} goal runs; errors: {sum(1 for r in runs if r.get('error'))}; "
             f"cost {sum(r.get('cost') or 0 for r in runs):.3f} USD; elapsed per run median "
             f"{med(r['elapsed_s'] for r in runs)} s, max {max((r['elapsed_s'] for r in runs), default=None)} s; "
             f"items answered {sum(len(r['rows']) for r in runs)} of {sum(len(r['keys']) for r in runs)}; "
             f"runs that changed the fixture: {sum(1 for r in runs if r.get('git_status_after'))}.", "",
             f"Spread over the three runs: max/min per item median {med(spreads):.2f}, 90th percentile "
             f"{sorted(spreads)[int(0.9 * (len(spreads) - 1))]:.2f}; median |log2(run / item median)| {med(devs):.2f}.",
             "", "## Fitted on goal A", "", "```json", json.dumps(factors, indent=1), "```", "",
             "## Validation on goals B and C", "", "| Group | n | Raw Haiku | Haiku × f | Self × f (0.5.0) |",
             "|---|---:|---:|---:|---:|"]

    def row(name, rows):
        if rows:
            r, h, s = med(errors(rows, "raw")), med(errors(rows, "haiku")), med(errors(rows, "self"))
            lines.append(f"| {name} | {len(rows)} | {r:.2f} | {h:.2f} | {s:.2f} |")
    row("all", test)
    for fam in sorted({i["family"] for i in test}):
        row(fam, [i for i in test if i["family"] == fam])
    for letter in ("B", "C"):
        row(f"goal {letter}", [i for i in test if i["goal"] == letter])
    for fixture in sorted({i["fixture"] for i in test}):
        row(fixture, [i for i in test if i["fixture"] == fixture])
    row("goal A (in-sample)", fit)
    lines += ["", "## Per goal run (validation)", "", "| Goal run | Σ measured | Σ Haiku × f | Σ self × f | Haiku err | Self err |",
              "|---|---:|---:|---:|---:|---:|"]
    goal_errs = {"haiku": [], "self": []}
    for gid in sorted({i["goal_run"] for i in test}):
        mine = [i for i in test if i["goal_run"] == gid]
        act = sum(i["actual"] for i in mine)
        hk = sum(i["haiku"] * factor(i["family"]) for i in mine)
        sf = sum(i["self_est"] * SELF.get(i["family"], SELF["default"]) for i in mine if i["self_est"])
        he, se = abs(log2(act / hk)), abs(log2(act / sf)) if sf else None
        goal_errs["haiku"].append(he)
        if se is not None:
            goal_errs["self"].append(se)
        lines.append(f"| {gid} | {act:.1f} | {hk:.1f} | {sf:.1f} | {he:.2f} | {'' if se is None else f'{se:.2f}'} |")
    lines += ["", f"Median per goal run: Haiku × f {med(goal_errs['haiku']):.2f}, self × f {med(goal_errs['self']):.2f}."]
    (LAB / "METRICS.md").write_text("\n".join(lines) + "\n")
    (LAB / "baseline-candidate.json").write_text(json.dumps({"haiku": factors}, indent=1) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
