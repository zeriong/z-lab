#!/usr/bin/env python3
"""SPEC.md's analysis. Usage: python3 analyze.py  → METRICS.md"""
import importlib.util
import json
from pathlib import Path
import re

LAB = Path(__file__).resolve().parent
RUNS = LAB / "runs"
REPLAYED = [LAB.parent / "eta-large-calibrate-0.7.0" / "runs", LAB.parent / "eta-isolated-run-r2-0.6.0" / "runs"]
SUBJECTS = {"0.7.0": LAB.parent / "eta-large-calibrate-0.7.0" / "subject" / "free-hands" / "scripts" / "eta.py",
            "fix": LAB / "subject" / "free-hands" / "scripts" / "eta.py"}


def module(name, path):
    spec = importlib.util.spec_from_file_location(f"eta_{name.replace('.', '_')}", path)
    loaded = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(loaded)
    return loaded


def lines(path):
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()] if path.exists() else []


def cells(root):
    if not root.exists():
        return []
    return sorted(p for p in root.iterdir() if (p / "DONE").exists() and (p / "summary.json").exists()
                  and "goals" in json.loads((p / "summary.json").read_text()))


def after(cell):
    notes = json.loads((cell / "summary.json").read_text())
    return notes, cell / f"free-hands-dir-after-{notes['goals'][0]}"


def replay(eta, folder):
    """{'le': (found, n), 'gt': (found, n), 'unestimated_gt': k} for one cell's final records."""
    text = (folder / "goal.md").read_text(encoding="utf-8")
    state = json.loads((folder / "eta.json").read_text())
    found = eta.estimates(folder, eta.run_of(state))
    known = state.get("items") or {}
    out = {"le": [0, 0], "gt": [0, 0]}
    for item in eta.checklist(text):
        side = "gt" if len(item[1]) > 200 else "le"
        out[side][1] += 1
        out[side][0] += eta.estimate_of(item, found, known)[0] is not None
    reopened = re.sub(r"^(\s*- )\[[xX-]\]", r"\1[ ]", text, flags=re.MULTILINE)
    _, keys = eta.unestimated(folder, reopened)
    out["unestimated_gt"] = sum(len(k) > 200 for k in keys)
    out["unestimated_le"] = sum(len(k) <= 200 for k in keys)
    return out


def main():
    etas = {name: module(name, path) for name, path in SUBJECTS.items()}
    out = ["# Metrics", "", "Generated by analyze.py.", "", "## R — replay of finished cells' records", "",
           "| Cell | Subject | items ≤ 200 with an estimate | items > 200 with an estimate | left to ask ≤ 200 | "
           "left to ask > 200 |", "|---|---|---:|---:|---:|---:|"]
    r_ok, r_more = True, 0
    for root in REPLAYED:
        for cell in cells(root):
            _, folder = after(cell)
            result = {name: replay(eta, folder) for name, eta in etas.items()}
            for name, res in result.items():
                out.append(f"| {root.parent.name}/{cell.name} | {name} | {res['le'][0]}/{res['le'][1]} | "
                           f"{res['gt'][0]}/{res['gt'][1]} | {res['unestimated_le']} | {res['unestimated_gt']} |")
            old, new = result["0.7.0"], result["fix"]
            r_ok &= new["le"][0] >= old["le"][0] and new["gt"][0] >= old["gt"][0]
            r_more += new["gt"][0] - old["gt"][0]
    out += ["", "## L — live cells (fixed subject)", "",
            "| Cell | cost USD | elapsed min | items | > 200 | estimate rows | distinct keys | max rows per key | "
            "finished | finished with est_min | finished whose key has an estimate row | active entries | with `+` |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    l_ok, live = True, cells(RUNS)
    for cell in live:
        notes, folder = after(cell)
        run = json.loads((folder / "eta.json").read_text())
        run_id = round(float(run.get("started") or 0), 3)
        rows = [e for e in lines(folder / "estimates.jsonl") if e.get("run") == run_id]
        per_key = {}
        for e in rows:
            per_key[e["item"]] = per_key.get(e["item"], 0) + 1
        timings = [t for t in lines(folder / "timings.jsonl") if t.get("outcome") == "done"]
        answered = {e["item"] for e in rows if e.get("minutes")}  # a row without minutes: asked, no answer
        keyed = [t for t in timings if t.get("item") in answered or t.get("was") in answered]
        with_est = [t for t in keyed if t.get("est_min")]
        text = (folder / "goal.md").read_text(encoding="utf-8")
        keys = [k for _, k, _, _ in etas["fix"].checklist(text)]
        entries = [w["status"]["value"] for w in lines(cell / "lab" / "witness.jsonl")
                   if w.get("status") and str(w["status"].get("value", "")).startswith("active")]
        plus = sum(v.rstrip().endswith("+") for v in entries)
        top = max(per_key.values()) if per_key else 0
        out.append(f"| {cell.name} | {notes.get('cost', 0):.2f} | {sum(r.get('elapsed_s') or 0 for r in notes['runs']) / 60:.1f} | "
                   f"{len(keys)} | {sum(len(k) > 200 for k in keys)} | {len(rows)} | {len(per_key)} | {top} | "
                   f"{len(timings)} | {sum(1 for t in timings if t.get('est_min'))} | {len(with_est)}/{len(keyed)} | "
                   f"{len(entries)} | {plus} |")
        l_ok &= top <= 1 and len(with_est) == len(keyed)
    out += ["", "## Dashboard in the live cells", "",
            "| Cell | Marks | Shown | Shown left min | Wall min to the last finished item |", "|---|---|---|---:|---:|"]
    for cell in live:
        witness = lines(cell / "lab" / "witness.jsonl")
        done_at = [w["at"] for i, w in enumerate(witness) if i and w.get("marks", "").count("x") >
                   witness[i - 1].get("marks", "").count("x")]
        last = max(done_at) if done_at else None
        for w in witness:
            status = w.get("status") or {}
            if not status:
                continue
            left, detail = None, status.get("detail") or ""
            if "left" in detail:
                part = detail.split("left")[0].strip().split()[-1].lstrip("~")
                hours, _, mins = part.partition("h")
                left = (int(hours) * 60 + int(mins.rstrip("m"))) if mins else int(part.rstrip("m"))
            wall = round((last - w["at"]) / 60, 1) if last and last >= w["at"] else None
            out.append(f"| {cell.name} | `{w.get('marks')}` | {status.get('value')} | {left} | {wall} |")
    keep = r_ok and r_more > 0 and l_ok and len(live) == 2
    out += ["", f"R: the fix finds every estimate 0.7.0 finds: {r_ok}; more items over 200 characters: {r_more}. "
                f"L: one row per key and est_min on every keyed finished item in both cells: {l_ok and len(live) == 2}.",
            "", f"**Decision (SPEC rule): {'keep the fix' if keep else 'drop the fix'}**", ""]
    (LAB / "METRICS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
