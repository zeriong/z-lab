#!/usr/bin/env python3
"""SPEC.md's replay. Usage: python3 replay.py  → METRICS.md"""
import importlib.util
import math
from pathlib import Path
import statistics

LAB = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("local", LAB.parent / "eta-local-replay-0.7.0" / "replay.py")
local = importlib.util.module_from_spec(spec)
spec.loader.exec_module(local)
MOMENTS = (0.5, 1, 2, 4)
METHODS = (("R0", None), ("R1 w=0.5", 0.5), ("R1 w=1", 1.0))


def remaining(method_w, t, pred_i, later):
    if method_w is None or t <= pred_i:
        return max(pred_i - t, 0.1 * pred_i) + sum(later)
    s = t / pred_i
    return 0.5 * t + sum(p * s ** method_w for p in later)


def evaluate(rows):
    projects = {}
    for r in rows:
        projects.setdefault(r["project"], []).append(r)
    errors = {(name, m): [] for name, _ in METHODS for m in MOMENTS}
    for prows in projects.values():
        for index, r in enumerate(prows):
            goal_rows = [x for x in prows if x["goal"] == r["goal"]]
            position = goal_rows.index(r)
            prior = prows[:index]
            pred = lambda x: x["est"] * local.ratio(x, prior, "P0")  # noqa: E731
            pred_i = pred(r)
            later = [pred(x) for x in goal_rows[position + 1:]]
            later_actual = sum(x["actual"] for x in goal_rows[position + 1:])
            for m in MOMENTS:
                t = m * pred_i
                if r["actual"] <= t:
                    continue
                truth = (r["actual"] - t) + later_actual
                for name, w in METHODS:
                    errors[(name, m)].append(abs(math.log2(truth / remaining(w, t, pred_i, later))))
    return errors


def main():
    sets = local.datasets()
    lines = ["# Metrics", "", "Generated by replay.py. Error = |log2(measured remainder / predicted remainder)| at the "
             "moments an item had run m × its prediction and was still running.", ""]
    for name, rows in sets.items():
        errors = evaluate(rows)
        lines += [f"## {name}", "", "| Predictor | " + " | ".join(f"m={m} (n)" for m in MOMENTS) + " |",
                  "|---|" + "---:|" * len(MOMENTS)]
        for method, _ in METHODS:
            cells = [f"{statistics.median(errors[(method, m)]):.2f} ({len(errors[(method, m)])})"
                     if errors[(method, m)] else "–" for m in MOMENTS]
            lines.append(f"| {method} | " + " | ".join(cells) + " |")
        lines.append("")
    (LAB / "METRICS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
