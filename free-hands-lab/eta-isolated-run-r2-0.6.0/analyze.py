#!/usr/bin/env python3
"""SPEC.md's analysis. Usage: python3 analyze.py  → METRICS.md"""
import calendar
import gzip
import json
from pathlib import Path
import re
import time

LAB = Path(__file__).resolve().parent
RUNS = LAB / "runs"
LAB_PATH = re.compile(r"[^\s\"']*fh-eta[^\s\"']*")
LEAK = re.compile(r"\(~\s*\d+(?:\.\d+)?\s*m|estimate|estimates\.jsonl|\bETA\b|eta\.json|timings\.jsonl", re.I)


def epoch(stamp):
    return calendar.timegm(time.strptime(stamp, "%Y-%m-%dT%H:%M:%SZ"))


def rows(path):
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()] if path.exists() else []


def leaks(stream):
    """Every hit of the leak pattern in what the main agent saw or wrote: its text, tool inputs and results, hook
    outputs (with a little context)."""
    hits = []
    for line in gzip.open(stream, "rt"):
        try:
            e = json.loads(line)
        except ValueError:
            continue
        places = []
        if e.get("type") == "assistant" and not e.get("parent_tool_use_id"):
            for b in (e.get("message") or {}).get("content") or []:
                if b.get("type") == "text":
                    places.append(("assistant text", b.get("text") or ""))
                elif b.get("type") == "tool_use":
                    places.append((f"tool input {b.get('name')}", json.dumps(b.get("input"))))
        elif e.get("type") == "user" and not e.get("parent_tool_use_id"):
            content = (e.get("message") or {}).get("content")
            for b in content if isinstance(content, list) else [{"type": "text", "text": str(content)}]:
                if isinstance(b, dict) and b.get("type") == "tool_result":
                    places.append(("tool result", json.dumps(b.get("content"))))
                elif isinstance(b, dict) and b.get("type") == "text":
                    places.append(("user text", b.get("text") or ""))
        elif e.get("type") == "system" and e.get("subtype") == "hook_response":
            places.append((f"hook output {e.get('hook_name')}", str(e.get("output") or "")))
        for where, text in places:
            text = LAB_PATH.sub("<lab path>", text)  # the lab's temporary folders are named fh-eta-… (round 1 defect)
            for m in LEAK.finditer(text):
                hits.append((where, text[max(0, m.start() - 60):m.end() + 60].replace("\\n", " ")))
    return hits


def main():
    lines = ["# Metrics", "", "Generated by analyze.py from runs/*/.", ""]
    for cell in sorted(p for p in RUNS.iterdir() if p.is_dir() and p.name not in ("V00", "band")
                       and (p / "DONE").exists()):
        notes = json.loads((cell / "summary.json").read_text())
        run = notes["runs"][0]
        folder = cell / f"free-hands-dir-after-{run['goal']}"
        witness = rows(cell / "lab" / "witness.jsonl")
        first = next((w["at"] for w in witness if w.get("marks")), None)
        est = rows(folder / "estimates.jsonl")
        timing = rows(folder / "timings.jsonl")
        hits = leaks(cell / f"stream-{run['goal']}.jsonl.gz")
        hook_outputs = [h for h in hits if h[0].startswith("hook output")]
        lines += [f"## {cell.name}", "",
                  f"- Main session: exit {run.get('exit')}, {run.get('elapsed_s')} s, {run.get('cost') or 0:.2f} USD, "
                  f"{run.get('tool_uses')} tool uses; tests after: exit {run.get('tests_after', {}).get('exit')}.",
                  f"- Leak hits in the main stream: {len(hits)} (hook outputs: {len(hook_outputs)}).",
                  *[f"  - {where}: …{context}…" for where, context in hits[:20]],
                  f"- Estimates: {len(est)} rows ({sum(1 for r in est if r.get('minutes'))} with minutes) in "
                  f"{len({r.get('at') for r in est})} estimator runs; first row "
                  f"{(epoch(est[0]['at']) - first) if est and first else 'n/a'} s after the first checklist; estimator "
                  f"seconds {sorted({r.get('seconds') for r in est})}; model {sorted({str(r.get('model')) for r in est})}; "
                  f"cost {sum({r.get('at'): r.get('cost_usd') or 0 for r in est}.values()):.4f} USD; "
                  f"estimator.log: {(folder / 'estimator.log').read_text().strip() if (folder / 'estimator.log').exists() else 'none'}.",
                  f"- Estimator lock free after the session: {run.get('estimator_lock_free')}; transcripts created during "
                  f"the cell: {len(notes.get('new_transcripts') or [])} (the main session's own: 1 expected).",
                  f"- Timing rows: {len(timing)}; with an estimate in the row {sum(1 for r in timing if r.get('est_min'))}; "
                  f"estimators {sorted({str(r.get('estimator')) for r in timing})}.",
                  "- Dashboard values the witness recorded:",
                  *[f"  - {w['marks']!r}: {w['status'].get('value')} | {w['status'].get('detail')}"
                    for w in witness if w.get("status")], ""]
    band = RUNS / "band" / "summary.json"
    if band.exists():
        notes = json.loads(band.read_text())
        shots = json.loads((RUNS / "band" / "screens.json").read_text())
        start = notes.get("prompt_at") or 0
        changes, previous = [], None
        for s in shots:
            if s.get("entry") != previous:
                changes.append((round(s["at"] - start, 1), s.get("entry")))
                previous = s.get("entry")
        est = [json.loads(l) for l in (notes.get("estimates.jsonl") or "").splitlines() if l.strip()]
        lines += ["## band", "", f"- Elapsed {notes.get('elapsed_ms')} ms; turn log "
                  f"{[(r['event'], round(r['at'] / 1000 - start, 1)) for r in notes.get('turn_log', [])]}.",
                  f"- Estimates: {len(est)} rows, {sum(1 for r in est if r.get('minutes'))} with minutes; "
                  f"estimator.log: {(notes.get('estimator.log') or 'none').strip()}.",
                  f"- Values before turn.complete: {notes.get('values_before_turn_complete')}.",
                  "- Entry changes (seconds after the prompt):", *[f"  - {t}: {v}" for t, v in changes], ""]
    (LAB / "METRICS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
