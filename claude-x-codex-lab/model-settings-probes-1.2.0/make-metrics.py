#!/usr/bin/env python3
"""Generate METRICS.md from runs/*/metrics.json and summary.json. Usage: python3 make-metrics.py"""
import json
from pathlib import Path

LAB = Path(__file__).resolve().parent
lines = ["# METRICS — model-settings-probes-1.2.0", "", "Generated by `make-metrics.py` from `runs/`. No arms; deltas N/A.", "",
         f"Product: `{(LAB / 'runs/PRODUCT').read_text().split()[1]}` · versions: "
         + " · ".join(l.strip() for l in (LAB / 'runs/VERSIONS').read_text().splitlines() if l.strip()), "",
         "| Case | Subprocesses | Elapsed total (ms) | Tokens (CLI-reported) |", "|---|---|---|---|"]
for case in sorted(p for p in (LAB / "runs").iterdir() if p.is_dir()):
    rows = json.loads((case / "metrics.json").read_text())
    summary = json.loads((case / "summary.json").read_text())
    tokens = []
    for key, value in summary.items():
        if isinstance(value, dict):
            usage = value.get("usage")
            if isinstance(usage, dict):
                tokens.append(f"{key}: in {usage.get('input_tokens', 0) + usage.get('cache_creation_input_tokens', 0) + usage.get('cache_read_input_tokens', 0)} / out {usage.get('output_tokens', 0)}")
            if value.get("tokens_used") is not None:
                tokens.append(f"{key}: {value['tokens_used']}")
    lines.append(f"| {case.name} | {len(rows)} | {sum(r['elapsed_ms'] for r in rows)} | {'; '.join(tokens) or 'not measured'} |")
lines += ["", "Per subprocess: `runs/<case>/metrics.json`. Claude tokens = input + cache_creation + cache_read / output, from the",
          "`result` event's `usage`; Codex tokens = the run's `tokens used` line.", ""]
(LAB / "METRICS.md").write_text("\n".join(lines))
print("\n".join(lines))
