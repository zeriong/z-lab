#!/usr/bin/env python3
"""Generate METRICS.md from runs/*/metrics.json and summary.json. Usage: python3 make-metrics.py"""
import json
from pathlib import Path

LAB = Path(__file__).resolve().parent
runs = LAB / "runs"
lines = ["# METRICS — model-settings-1.2.0", "", "Generated by `make-metrics.py` from `runs/`. No arms; deltas N/A.", "",
         f"Product: `{(runs / 'PRODUCT').read_text().split()[1]}` · versions: "
         + " · ".join(l.strip() for l in (runs / 'VERSIONS').read_text().splitlines() if l.strip()), "",
         "| Case | Subprocesses | Elapsed total (ms) | Tokens (CLI-reported) |", "|---|---|---|---|"]
for case in sorted(p for p in runs.iterdir() if p.is_dir()):
    rows = json.loads((case / "metrics.json").read_text())
    summary = json.loads((case / "summary.json").read_text())
    tokens = []
    for key, value in summary.items():
        if not isinstance(value, dict):
            continue
        usage = value.get("usage")
        if isinstance(usage, dict):
            total = sum(usage.get(k, 0) for k in ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens"))
            tokens.append(f"{key}: in {total} / out {usage.get('output_tokens', 0)}")
        elif isinstance(usage, list) and usage:
            u = usage[-1]
            tokens.append(f"{key}: in {u.get('input_tokens', 0)} (cached {u.get('cached_input_tokens', 0)}) / out {u.get('output_tokens', 0)}")
    lines.append(f"| {case.name} | {len(rows)} | {sum(r['elapsed_ms'] for r in rows)} | {'; '.join(tokens) or 'none (no model call)'} |")
status = json.loads((runs / "M02" / "summary.json").read_text())["status_ms"]
lines += ["", "M02 status command wall time (ms, five runs each, includes interpreter start): "
          + "; ".join(f"{role} {values} (max {max(values)})" for role, values in status.items()), "",
          "Claude tokens = input + cache_creation + cache_read / output from the result's `usage`; Codex tokens = the last",
          "`turn.completed` usage. Per subprocess: `runs/<case>/metrics.json`.", ""]
(LAB / "METRICS.md").write_text("\n".join(lines))
print("\n".join(lines))
