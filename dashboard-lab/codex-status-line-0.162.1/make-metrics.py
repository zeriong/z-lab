#!/usr/bin/env python3
"""Generate METRICS.md from runs/*/summary.json. Usage: python3 make-metrics.py"""
import json
from pathlib import Path

LAB = Path(__file__).resolve().parent
lines = ["# Metrics", "", "Generated by make-metrics.py from runs/*/summary.json.", "", "| Case | Elapsed ms |",
         "|---|---:|"]
for case in sorted(p for p in (LAB / "runs").iterdir() if p.is_dir() and p.name != "V00"):
    lines.append(f"| {case.name} | {json.loads((case / 'summary.json').read_text()).get('elapsed_ms')} |")
lines += ["", "Elapsed ms = from creating the temporary home to the last snapshot, fixed waits included. The TUI shows no "
          "token counts, so none are recorded. Deltas: N/A."]
(LAB / "METRICS.md").write_text("\n".join(lines) + "\n")
